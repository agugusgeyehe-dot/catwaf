#!/usr/bin/env node

// Regenerates docs/settings.md from backend/services/settings/schema.js.
//
// The settings reference is generated rather than written because it is a
// mechanical restatement of the schema, and a hand-maintained copy of ~37
// groups would be wrong within a release. Run this after adding a setting:
//
//     node scripts/gen-settings-docs.js
//
// It writes the file and prints what changed, so it is safe to run in CI to
// check the reference is current.

const fs = require('fs')
const path = require('path')
const os = require('os')

// The schema module reaches for the database on load, so give it a scratch
// one — nothing here reads or writes real configuration.
const WORK = fs.mkdtempSync(path.join(os.tmpdir(), 'catwaf-docs-'))
process.env.DB_DIR = path.join(WORK, 'db')
process.env.JWT_SECRET = process.env.JWT_SECRET || 'f'.repeat(64)
fs.mkdirSync(process.env.DB_DIR, { recursive: true })
process.on('exit', () => { try { fs.rmSync(WORK, { recursive: true, force: true }) } catch {} })

const settings = require('../backend/services/settings')

const TARGET = path.join(__dirname, '..', 'docs', 'settings.md')

const TYPE_LABEL = {
  bool: 'switch',
  int: 'number',
  string: 'text',
  text: 'multi-line text',
  enum: 'choice',
  list: 'list',
  records: 'rows',
  map: 'map',
}

function escape(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\n+/g, ' ')
}

function defaultFor(field) {
  if (field.write_only) return '_(secret)_'
  const v = field.default
  if (Array.isArray(v)) return v.length ? '`' + v.join(', ') + '`' : '_(empty)_'
  if (v === '' || v === null || v === undefined) return '_(unset)_'
  if (typeof v === 'object') return '`' + JSON.stringify(v) + '`'
  return '`' + String(v) + '`'
}

function typeFor(field) {
  const base = TYPE_LABEL[field.type] || field.type
  if (field.type === 'enum' && field.values) return `${base}: ${field.values.map(v => '`' + (v === '' ? '(none)' : v) + '`').join(', ')}`
  if (field.type === 'int' && (field.min !== null || field.max !== null)) {
    const range = [field.min ?? '', field.max ?? ''].join('–')
    return `${base} (${range})`
  }
  return base
}

function build() {
  const described = settings.describe()
  const out = []

  out.push('# Settings reference')
  out.push('')
  out.push('<!-- Generated by scripts/gen-settings-docs.js — do not edit by hand. -->')
  out.push('')
  out.push('Every setting below is reachable three ways, all of which go through the')
  out.push('same validation and the same apply pipeline:')
  out.push('')
  out.push('- the dashboard, which builds its controls from this schema at runtime;')
  out.push('- `catwaf settings <group> field=value` — see [the CLI reference](cli.md#catwaf-settings);')
  out.push('- `PATCH /api/settings/<group>`.')
  out.push('')
  out.push('A change is written, rendered into the Caddyfile, validated by Caddy, and')
  out.push('only then applied. If the result would not load, the previous')
  out.push('configuration is kept and the change is reported as rejected.')
  out.push('')
  out.push('Fields marked _(secret)_ are write-only: they can be set, but are never')
  out.push('sent back to the browser or printed by the CLI.')
  out.push('')
  out.push('Some settings depend on an optional Caddy module. When one is missing,')
  out.push('CatWAF **skips** that directive rather than emitting something Caddy would')
  out.push('reject and taking the site down with it — and reports the skip. Run')
  out.push('`catwaf doctor` to see what the installed build supports and what was left')
  out.push('out.')
  out.push('')

  out.push('## Groups')
  out.push('')
  out.push('| Group | What it covers |')
  out.push('|---|---|')
  for (const [group, def] of Object.entries(described)) {
    out.push(`| [\`${group}\`](#${group}) | ${escape(def.summary)} |`)
  }
  out.push('')

  for (const [group, def] of Object.entries(described)) {
    out.push(`## ${group}`)
    out.push('')
    out.push(`**${def.label}**${def.secret ? ' · contains secrets' : ''}${def.advanced ? ' · advanced' : ''}`)
    out.push('')
    out.push(escape(def.summary))
    out.push('')
    out.push('| Field | Type | Default | Meaning |')
    out.push('|---|---|---|---|')
    for (const field of def.fields) {
      if (field.name.endsWith('_set')) continue
      out.push(`| \`${field.name}\` | ${typeFor(field)} | ${defaultFor(field)} | ${escape(field.help || field.label)} |`)
    }
    out.push('')
    for (const field of def.fields) {
      if (!field.fields) continue
      out.push(`Each row of \`${field.name}\` has:`)
      out.push('')
      out.push('| Column | Type | Default |')
      out.push('|---|---|---|')
      for (const sub of field.fields) {
        out.push(`| \`${sub.name}\` | ${typeFor(sub)} | ${defaultFor(sub)} |`)
      }
      out.push('')
    }
  }

  const groups = Object.keys(described).length
  const fields = Object.values(described).reduce((n, d) => n + d.fields.filter(f => !f.name.endsWith('_set')).length, 0)
  out.push('---')
  out.push('')
  out.push(`${groups} groups, ${fields} settings.`)
  out.push('')

  return out.join('\n')
}

const next = build()
const previous = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : null

if (previous === next) {
  console.log('docs/settings.md is up to date.')
  process.exit(0)
}

if (process.argv.includes('--check')) {
  console.error('docs/settings.md is out of date — run `node scripts/gen-settings-docs.js`.')
  process.exit(1)
}

fs.writeFileSync(TARGET, next)
console.log(previous === null ? 'Wrote docs/settings.md.' : 'Updated docs/settings.md.')
